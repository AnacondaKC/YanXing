import assert from 'node:assert/strict'
import {randomUUID} from 'node:crypto'

/** Extends the real browser session; all mutations target its synthetic native database. */
export async function runP5BrowserChecks({api,page,evaluate,click,navigate,text,waitFor,screenshot,base,projectId,reportId}) {
  await page('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false})
  const source=await evaluate('(async()=>{const response=await fetch("/api/reports/'+reportId+'/file");if(!response.ok)throw Error("source unavailable");return [...new Uint8Array(await response.arrayBuffer())]})()')
  const load=async id=>(await api('/api/projects/'+id)).body
  async function submit({id,stageId,kind,status=201}){
    const detail=await load(id),stage=detail.stages.find(group=>group.stage.id===stageId).stage
    const prepared=await evaluate('(async()=>{const token=document.cookie.split("; ").find(x=>x.split("=")[0].endsWith("yanxing_csrf"))?.split("=").slice(1).join("=");const response=await fetch("/api/projects/'+id+'/report-uploads?fileName=p5-report.docx",{method:"POST",headers:{"Content-Type":"application/octet-stream","x-yanxing-csrf":decodeURIComponent(token??"")},body:new Uint8Array('+JSON.stringify(source)+')});return {status:response.status,body:await response.json()}})()')
    assert.equal(prepared.status,201,JSON.stringify(prepared.body))
    const command={uploadId:prepared.body.id,stageId,reportKind:kind,expectedPlanRevision:detail.workflow.planRevision,expectedWorkflowRevision:detail.workflow.workflowRevision,expectedCompletionRevision:stage.completionRevision,expectedCompletionReportId:stage.currentCompletionReportId??null}
    const result=await api('/api/projects/'+id+'/reports',command,{method:'POST',headers:{'Idempotency-Key':randomUUID()}})
    assert.equal(result.status,status,JSON.stringify(result.body))
    return result.body.receipt??result.body
  }
  let detail=await load(projectId)
  const first=detail.stages[0].stage, last=detail.stages.at(-1).stage
  const completedAt=first.completedAt
  await submit({id:projectId,stageId:first.id,kind:'update',status:409})
  assert.equal((await load(projectId)).project.submittedReportCount,1)
  const replacement=await submit({id:projectId,stageId:first.id,kind:'completion'})
  detail=await load(projectId)
  assert.equal(detail.stages[0].stage.completedAt,completedAt)
  assert.equal(detail.stages[1].stage.lifecycleStatus,'in_progress')
  assert.equal(detail.stages[0].reports[0].stageVersion,2)
  assert.equal((await api('/api/reports/'+reportId)).body.labels.roleLabel,'阶段更新报告')
  assert.equal((await api('/api/reports/'+replacement.reportId)).body.comparison.status,'available')
  assert.equal((await api('/api/reports/'+replacement.reportId)).body.comparison.scoreDelta,undefined)
  assert.equal((await api('/api/reports/'+reportId,{reason:'P5删除已被接替成果'},{method:'DELETE'})).status,200)
  assert.equal((await api('/api/reports/'+reportId)).status,404)
  assert.equal((await api('/api/reports/'+replacement.reportId)).body.comparison.status,'unavailable')
  const final=await submit({id:projectId,stageId:last.id,kind:'completion'})
  assert.equal((await api('/api/reports/'+final.reportId)).body.comparison.reason,'first_stage_submission')
  const early=await submit({id:projectId,stageId:first.id,kind:'completion'})
  detail=await load(projectId)
  assert.equal(detail.latestSubmission.id,early.reportId)
  assert.equal(detail.selected.reportId,final.reportId)
  assert.equal(detail.stages[0].reports[0].stageVersion,3)
  assert.equal(detail.stages.filter(group=>group.stage.lifecycleStatus==='in_progress').length,0)
  await navigate(base+'/?view=dashboard&project='+projectId)
  await waitFor(async()=>(await text()).includes(last.title),'completed project defaults to last-stage completion')
  await screenshot('09-completed-project-after-early-backfill')
  assert.equal(await evaluate('[...document.querySelectorAll("button")].some(button=>/调整研究计划|编辑课题信息/.test(button.innerText))'),false,'project pages no longer expose onboarding plan or metadata editors')
  await screenshot('10-frozen-plan')
  await navigate(base+'/?view=content&project='+projectId+'&report='+final.reportId)
  await waitFor(()=>evaluate('[...document.querySelectorAll("iframe")].some(frame=>frame.contentDocument?.body.innerText.includes("研究目标是建立可验证"))'),'native DOCX viewer')
  assert.equal(await evaluate('Boolean(document.querySelector("header [aria-label=阶段与报告选择]"))'),false,'original document omits header stage/report controls')
  await screenshot('11-retained-original-document')
  const created=await api('/api/projects',{title:'P5跳阶段课题',objective:'验证跳阶段与补交',description:'隔离验收数据',stages:[1,2,3].map(n=>({id:'p5-stage-'+n,title:'研究阶段'+n,description:'阶段研究内容',plannedEndAt:'2031-01-01'}))})
  assert.equal(created.status,201,JSON.stringify(created.body))
  const skippedProject=created.body.project.id
  await submit({id:skippedProject,stageId:'p5-stage-3',kind:'update'})
  const before=await load(skippedProject)
  assert.equal(before.stages[0].skippedEmpty,true)
  const backfill=await submit({id:skippedProject,stageId:'p5-stage-1',kind:'completion'})
  const after=await load(skippedProject)
  assert.equal(after.stages[0].stage.completedAt,before.stages[0].stage.completedAt)
  assert.equal(after.selected.stageId,'p5-stage-3')
  assert.equal((await api('/api/reports/'+backfill.reportId)).body.comparison.reason,'first_stage_submission')
  await navigate(base+'/?view=history&project='+skippedProject)
  await waitFor(async()=>(await text()).includes('跳过，暂无报告'),'skipped empty stage label in original history')
  assert.equal(await evaluate('Boolean(document.querySelector("header [aria-label=阶段与报告选择]"))'),false,'history omits header stage/report controls')
  await screenshot('12-skipped-stage-backfill')
  const reader=await api('/api/admin/users',{username:'p5-reader',displayName:'P5协作研究员',password:'p5-reader-test-password',role:'researcher'})
  assert.equal(reader.status,201)
  const membership=await api('/api/admin/projects/'+projectId+'/members')
  const members=membership.body.members.map(member=>({userId:member.userId,role:member.role}))
  assert.equal((await api('/api/admin/projects/'+projectId+'/members',{revision:membership.body.revision,members:[...members,{userId:reader.body.user.id,role:'editor'}]},{method:'PUT'})).status,200)
  await api('/api/auth/logout',{})
  assert.equal((await api('/api/auth/login',{username:'p5-reader',password:'p5-reader-test-password'})).status,200)
  await navigate(base+'/?view=dashboard&project='+projectId)
  await waitFor(async()=>(await text()).includes('P5协作研究员'),'read-only collaborator workspace')
  assert.equal(await evaluate('[...document.querySelectorAll("button")].some(button=>button.innerText.trim()==="提交报告")'),false)
  for(const operation of ['analyze','insight'])assert.equal((await api('/api/reports/'+final.reportId+'/'+operation,{})).status,403)
  assert.equal((await api('/api/reports/'+replacement.reportId,{reason:'协作者越权尝试'},{method:'DELETE'})).status,403)
  assert.equal((await api('/api/reports/'+final.reportId)).status,200)
  const scoreWidth=await evaluate('[...document.querySelectorAll("h2")].find(heading=>heading.innerText==="综合评分")?.closest(".yx-dashboard-card")?.getBoundingClientRect().width')
  assert.ok(scoreWidth>=280,'score card must use its container width rather than clipped viewport-xl columns')
  assert.equal(await evaluate('[...document.querySelectorAll("aside[aria-label=课题模块外挂导航] nav")].filter(el=>el.getBoundingClientRect().width>0).every(el=>el.getBoundingClientRect().height<60)'),true,'narrow desktop keeps original compact horizontal tabs')
  await screenshot('13-read-only-collaborator')
  await page('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
  await waitFor(()=>evaluate('innerWidth===390'),'populated mobile viewport')
  assert.equal(await evaluate('document.documentElement.scrollWidth>innerWidth+1'),false,'populated mobile horizontal overflow')
  const mobileScoreWidth=await evaluate('[...document.querySelectorAll("h2")].find(heading=>heading.innerText==="综合评分")?.closest(".yx-dashboard-card")?.getBoundingClientRect().width')
  assert.ok(mobileScoreWidth>=280&&mobileScoreWidth<=390,'mobile score remains legible')
  await screenshot('14-mobile-populated-report')
  await evaluate('[...document.querySelectorAll(".yx-dashboard-card")].at(-1).scrollIntoView({block:"end"})')
  assert.equal(await evaluate('[...document.querySelectorAll(".yx-dashboard-card")].at(-1).getBoundingClientRect().bottom<=innerHeight+1'),true,'mobile lower cards remain reachable')
  await screenshot('15-mobile-report-bottom')
  await page('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false})
  await navigate(base+'/?view=overview')
  await waitFor(()=>evaluate('Boolean(document.querySelector("[aria-label=分析质量全景]"))'),'restored overview panel')
  await screenshot('16-restored-overview')
  await navigate(base+'/?view=reports')
  await waitFor(()=>evaluate('Boolean(document.querySelector("input[placeholder^=搜索报告名称]"))'),'restored searchable report repository')
  await waitFor(()=>evaluate('Boolean(document.querySelector(".yx-repository-content button[aria-expanded=false]"))'),'original collapsible project group')
  await evaluate('document.querySelector(".yx-repository-content button[aria-expanded=false]").click()')
  await waitFor(()=>evaluate('document.querySelectorAll("tbody tr").length>0'),'original grouped report rows')
  await screenshot('17-restored-report-library')
  await navigate(base+'/?view=insight&project='+projectId+'&report='+final.reportId)
  await waitFor(()=>evaluate('Boolean(document.querySelector("[aria-label=报告洞察启动面板]"))'),'restored insight launch panel')
  assert.equal(await evaluate('Boolean(document.querySelector("header [aria-label=阶段与报告选择]"))'),false,'insight omits header stage/report controls')
  await screenshot('18-restored-insight')
  return {checks:['backfill','retained-current-stage','superseded-deletion','no-score-zero','no-version-reuse','first-stage-comparison-hidden','frozen-plan','docx-viewer','skipped-empty','collaborator-read-only','populated-mobile-layout','original-overview','original-report-library','original-insight','compact-project-tabs'],extraScreenshots:10}
}
